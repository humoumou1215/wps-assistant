"""Create small deterministic OOXML inputs for the live WPS integration suite.

The API observations/assertions are made by real WPS, not by this generator.
The files contain only stable seed text/values and are created in a temp dir.
"""
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile
import sys


def write_zip(path: Path, entries: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with ZipFile(path, "w", ZIP_DEFLATED) as archive:
        for name, contents in entries.items():
            archive.writestr(name, contents.encode("utf-8"))


